-- Esquema inicial para la migración. Aplicar solo a una base nueva y respaldada.
-- No ejecutar sobre un esquema existente: el error evita modificarlo.
BEGIN;

CREATE SCHEMA academy;
REVOKE ALL ON SCHEMA academy FROM PUBLIC;

CREATE TABLE academy.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  "passwordHash" text NOT NULL,
  name text,
  email text,
  avatar text,
  role text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  "createdAt" timestamptz NOT NULL,
  "updatedAt" timestamptz NOT NULL,
  "lastSignInAt" timestamptz NOT NULL
);

CREATE TABLE academy.module_progress (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL REFERENCES academy.users(id) ON DELETE CASCADE,
  "moduleId" integer NOT NULL,
  "completedAt" timestamptz NOT NULL,
  UNIQUE ("userId", "moduleId")
);

CREATE TABLE academy.quiz_attempts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL REFERENCES academy.users(id) ON DELETE CASCADE,
  score integer NOT NULL,
  total integer NOT NULL,
  answers text NOT NULL,
  "createdAt" timestamptz NOT NULL
);

CREATE TABLE academy.course_progress (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL REFERENCES academy.users(id) ON DELETE CASCADE,
  "courseVersion" text NOT NULL,
  "moduleId" integer NOT NULL,
  "completedAt" timestamptz NOT NULL,
  UNIQUE ("userId", "courseVersion", "moduleId")
);

CREATE TABLE academy.evaluation_attempts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL REFERENCES academy.users(id) ON DELETE CASCADE,
  "courseVersion" text NOT NULL,
  status text NOT NULL CHECK (status IN ('draft', 'submitted', 'abandoned')),
  questions text NOT NULL,
  answers text NOT NULL,
  revision integer NOT NULL DEFAULT 0,
  score integer,
  total integer NOT NULL,
  "passingPercent" integer NOT NULL,
  "createdAt" timestamptz NOT NULL,
  "submittedAt" timestamptz
);
CREATE UNIQUE INDEX evaluation_one_draft_idx
  ON academy.evaluation_attempts ("userId", "courseVersion") WHERE status = 'draft';

CREATE TABLE academy.recognitions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL REFERENCES academy.users(id) ON DELETE CASCADE,
  "courseVersion" text NOT NULL,
  "attemptId" integer NOT NULL REFERENCES academy.evaluation_attempts(id),
  folio text NOT NULL UNIQUE,
  "recipientName" text NOT NULL,
  issuer text NOT NULL,
  "courseTitle" text NOT NULL,
  score integer NOT NULL,
  total integer NOT NULL,
  "passingPercent" integer NOT NULL,
  "issuedAt" timestamptz NOT NULL,
  UNIQUE ("userId", "courseVersion")
);

REVOKE ALL ON ALL TABLES IN SCHEMA academy FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA academy FROM PUBLIC;
COMMIT;
